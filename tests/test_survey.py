import json
import unittest

from tests._support import HAS_GIT, TempRepo, run_cli
from stackfoundry.survey import survey

WEB = '<Project Sdk="Microsoft.NET.Sdk.Web"><ItemGroup>' \
      '<PackageReference Include="Microsoft.EntityFrameworkCore.SqlServer" /></ItemGroup></Project>'
WPF = '<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><OutputType>WinExe</OutputType>' \
      '<TargetFramework>net10.0-windows</TargetFramework><UseWPF>true</UseWPF></PropertyGroup>' \
      '<ItemGroup><PackageReference Include="CommunityToolkit.Mvvm" /></ItemGroup></Project>'
CLI = '<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><OutputType>Exe</OutputType></PropertyGroup></Project>'
TESTS = '<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><OutputType>Exe</OutputType></PropertyGroup><ItemGroup>' \
        '<PackageReference Include="Microsoft.NET.Test.Sdk" /><PackageReference Include="xunit.v3" />' \
        '</ItemGroup></Project>'
NUXT = json.dumps({"name": "web", "dependencies": {"nuxt": "4.0.0", "vue": "3.5.0"},
                   "devDependencies": {"typescript": "5.9.0", "vitest": "3.0.0"}})

FILES = {
    "src/Api/Api.csproj": WEB,
    "src/Desktop/Desktop.csproj": WPF,
    "src/Tool/Tool.csproj": CLI,
    "tests/Api.Tests/Api.Tests.csproj": TESTS,
    "web/package.json": NUXT,
    "web/nuxt.config.ts": "export default {}",
    "web/node_modules/vue/package.json": json.dumps({"name": "vue"}),
    "web/src/api-client/model.ts": "/* auto generated by OpenAPI Generator */\nexport type A = 1\n",
    ".github/workflows/ci.yml": "on: push",
    "docs/plans/x.md": "# x",
}


def techs(unit):
    return {(h["layer"], h["tech"]) for h in unit["hints"]}


class SurveyTests(unittest.TestCase):
    def check(self, result):
        units = {u["manifest"]: u for u in result["units"]}
        self.assertNotIn("web/node_modules/vue/package.json", units, "node_modules must be skipped")

        api, desktop = techs(units["src/Api/Api.csproj"]), techs(units["src/Desktop/Desktop.csproj"])
        # The point of the layer model: one language, two app models.
        self.assertIn(("language", "csharp"), api)
        self.assertIn(("language", "csharp"), desktop)
        self.assertIn(("app-model", "aspnet-core"), api)
        self.assertIn(("app-model", "wpf"), desktop)
        self.assertNotIn(("app-model", "wpf"), api)
        self.assertNotIn(("app-model", "aspnet-core"), desktop)
        self.assertIn(("capability", "efcore"), api)
        self.assertIn(("capability", "mvvm-toolkit"), desktop)
        self.assertNotIn(("app-model", "dotnet-console"), desktop, "a WPF app is not a console app")

        self.assertIn(("app-model", "dotnet-console"), techs(units["src/Tool/Tool.csproj"]))
        test_unit = units["tests/Api.Tests/Api.Tests.csproj"]
        self.assertTrue(test_unit["isTestProject"])
        self.assertIn(("tooling", "xunit"), techs(test_unit))
        self.assertNotIn(("app-model", "dotnet-console"), techs(test_unit), "a test runner host is not an app model")

        web = techs(units["web/package.json"])
        self.assertIn(("language", "typescript"), web)
        self.assertNotIn(("language", "javascript"), web)
        self.assertIn(("app-model", "nuxt-ssr"), web)
        self.assertNotIn(("app-model", "vue-spa"), web, "vue under nuxt is the nuxt app model")
        self.assertIn(("tooling", "vitest"), web)

        self.assertIn("web/src/api-client", result["generatedDirs"])
        self.assertIn("github-actions", result["infrastructure"]["ci"])
        self.assertEqual(result["docs"]["root"], "docs")

    def test_filesystem_walk(self):
        with TempRepo(FILES) as root:
            self.check(survey(root))

    @unittest.skipUnless(HAS_GIT, "git not installed")
    def test_git_listing_honours_gitignore_and_skips_worktrees(self):
        files = {**FILES, ".gitignore": "ignored/\n", "ignored/x/x.csproj": WEB,
                 ".claude/worktrees/copy/src/Api/Api.csproj": WEB}
        with TempRepo(files, git=True) as root:
            result = survey(root)
            self.check(result)
            manifests = {u["manifest"] for u in result["units"]}
            self.assertNotIn("ignored/x/x.csproj", manifests)
            self.assertFalse(any(m.startswith(".claude/worktrees/") for m in manifests))

    def test_cli_prints_json_and_writes_nothing(self):
        with TempRepo(FILES) as root:
            before = sorted(p.as_posix() for p in root.rglob("*"))
            proc = run_cli(["survey", str(root)])
            self.assertEqual(proc.returncode, 0, proc.stderr)
            self.assertEqual(json.loads(proc.stdout)["schemaVersion"], 1)
            self.assertEqual(before, sorted(p.as_posix() for p in root.rglob("*")))


if __name__ == "__main__":
    unittest.main()
